from __future__ import annotations

import json
from dataclasses import asdict
from pathlib import Path

import polars as pl

from evaluation.benchmark import BenchmarkResult
from evaluation.scorecard import ScoreCard


class ReportGenerator:
    """
    Enterprise Report Generator

    Generates:
    - benchmark_report.csv
    - scorecard.csv
    - scorecard.json
    - executive_report.txt
    """

    REPORT_DIR = Path("evaluation") / "reports"

    def __init__(self) -> None:
        self.REPORT_DIR.mkdir(parents=True, exist_ok=True)

    # --------------------------------------------------
    # CSV Reports
    # --------------------------------------------------

    def save_csv(
        self,
        benchmark: BenchmarkResult,
        score: ScoreCard,
    ) -> None:

        pl.DataFrame([asdict(benchmark)]).write_csv(
            self.REPORT_DIR / "benchmark_report.csv"
        )

        pl.DataFrame([asdict(score)]).write_csv(
            self.REPORT_DIR / "scorecard.csv"
        )

    # --------------------------------------------------
    # JSON Report
    # --------------------------------------------------

    def save_json(
        self,
        benchmark: BenchmarkResult,
        score: ScoreCard,
    ) -> None:

        payload = {
            "benchmark": asdict(benchmark),
            "scorecard": asdict(score),
        }

        with open(
            self.REPORT_DIR / "scorecard.json",
            "w",
            encoding="utf-8",
        ) as file:

            json.dump(payload, file, indent=4)

    # --------------------------------------------------
    # Executive TXT Report
    # --------------------------------------------------

    def save_text(
        self,
        benchmark: BenchmarkResult,
        score: ScoreCard,
    ) -> None:

        report = f"""
============================================================
 BUY OR WAIT • EXECUTIVE REPORT
============================================================

PERFORMANCE
-----------
Requests           : {benchmark.total_requests}
Worker Threads     : {benchmark.worker_threads}
Throughput         : {benchmark.throughput_rps} req/sec

P50 Latency        : {benchmark.p50_latency_ms} ms
P95 Latency        : {benchmark.p95_latency_ms} ms
P99 Latency        : {benchmark.p99_latency_ms} ms

CPU Time           : {benchmark.cpu_time_sec} sec
Wall Time          : {benchmark.wall_time_sec} sec
Peak Memory        : {benchmark.peak_memory_mb} MB

------------------------------------------------------------

AI QUALITY
----------
Accuracy           : {score.accuracy:.4f}
Precision          : {score.precision:.4f}
Recall             : {score.recall:.4f}
F1 Score           : {score.f1_score:.4f}

Money Score        : {score.affordability_score:.4f}
Schema Valid       : {score.schema_valid}

------------------------------------------------------------

ENTERPRISE SCORE

Final KPI          : {score.final_score}/100

============================================================
Generated by Buy Or Wait AI Financial Engine
============================================================
"""

        with open(
            self.REPORT_DIR / "executive_report.txt",
            "w",
            encoding="utf-8",
        ) as file:

            file.write(report.strip())

    # --------------------------------------------------
    # Generate All Reports
    # --------------------------------------------------

    def generate(
        self,
        benchmark: BenchmarkResult,
        score: ScoreCard,
    ) -> None:

        self.save_csv(benchmark, score)
        self.save_json(benchmark, score)
        self.save_text(benchmark, score)